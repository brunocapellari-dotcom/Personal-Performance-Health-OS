NOISE_ORDER = {"low": 0, "moderate": 1, "high": 2}


class ExerciseSelector:
    def __init__(self, exercises: tuple[Exercise, ...] = DEFAULT_EXERCISES):
        self.exercises = exercises

    def eligible(self, env: TrainingEnvironment, movement_pattern: str | None = None) -> tuple[Exercise, ...]:
        selected = []
        for ex in self.exercises:
            if env.environment not in ex.environments:
                continue
            if not ex.equipment.issubset(env.equipment):
                continue
            if ex.space_required_m2 > env.space_m2:
                continue
            if not ex.fixation_points_required.issubset(env.fixation_points):
                continue
            if NOISE_ORDER.get(ex.noise, 1) > NOISE_ORDER.get(env.noise_limit, 1):
                continue
            if movement_pattern and ex.movement_pattern != movement_pattern:
                continue
            selected.append(ex)
        return tuple(selected)

    def choose_one(self, env: TrainingEnvironment, movement_pattern: str) -> Exercise:
        options = self.eligible(env, movement_pattern)
        if not options:
            raise ValueError(f"No eligible exercise for movement pattern={movement_pattern}")
        return sorted(options, key=lambda x: (x.fatigue, -x.strength, x.exercise_id))[0]
